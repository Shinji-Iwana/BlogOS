{{-- ==========================================================
     対象ブログ選択
     ----------------------------------------------------------
     BlogOSで現在操作対象とするブログを選択する。

     Controllerから渡された$blogsには、
     blogsテーブルに登録されているブログが
     ID昇順で格納されている。

     選択リストでは、

     ・表示値
         blogs.name

     ・選択値
         blogs.id

     とする。

     valueとしてブログIDを保持することで、
     カテゴリ一覧などの各機能へ遷移する際に
     「現在どのブログを操作しているか」を
     blog_idとして利用できる。

     ブログが1件も存在しない場合は、
     ブログ登録画面へのリンクのみを表示する。

     ========================================================== --}}

@if ($blogs->isNotEmpty())

    <div>

        {{-- ======================================================
             対象ブログラベル
             ====================================================== --}}

        <label for="target-blog">
            対象ブログ
        </label>

        {{-- ======================================================
             対象ブログ選択リスト
             ------------------------------------------------------
             $blogsはBlogRepositoryから取得した
             blogsテーブルの全レコード。

             optionのvalueにはblogs.idを設定する。

             これにより、選択されたブログを
             IDで識別できる。

             先頭のoptionにはselectedを設定し、
             初期表示時には先頭ブログを選択状態にする。
             ====================================================== --}}

        <select id="target-blog">

            @foreach ($blogs as $index => $blog)

                <option
                    value="{{ $blog->id }}"
                    @if ($index === 0) selected @endif
                >
                    {{ $blog->name }}
                </option>

            @endforeach

        </select>

    </div>
    <p><a href="{{ route('blog-register') }}">ブログ登録ページへ</a></p>
    <p><a href="{{ route('blog-list') }}">ブログ一覧ページへ</a></p>
    <p><a href="{{ route('blog-history-list') }}">ブログ変更履歴一覧ページへ</a></p>
    <p><a href="{{ route('category-list', $blogs->first()->id) }}">カテゴリ一覧ページへ</a></p>
    <p><a href="{{ route('category-history-list', $blogs->first()->id) }}">カテゴリ変更履歴一覧ページへ</a></p>

@else

    {{-- ==========================================================
         ブログ未登録時
         ----------------------------------------------------------
         blogsテーブルにブログが1件も存在しない場合。

         この場合は対象ブログを選択する必要がないため、
         ブログ登録画面への導線のみを表示する。
         ========================================================== --}}

    <p>
        登録されているブログがありません。
    </p>

    <p><a href="{{ route('blog-register') }}">ブログ登録ページへ</a></p>

@endif

<form method="POST" action="{{ route('logout') }}" style="display:inline;">
    @csrf
    <button type="submit">ログアウト</button>
</form>
@endsection
