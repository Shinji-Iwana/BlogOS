<!DOCTYPE html>
<html lang="ja">
<head>

    {{-- ==========================================================
         基本的なHTML設定
         ----------------------------------------------------------
         UTF-8で日本語を正しく表示する。
         ========================================================== --}}
    <meta charset="UTF-8">

    {{-- ==========================================================
         ページタイトル
         ----------------------------------------------------------
         ブラウザのタブなどに表示するページタイトル。
         ========================================================== --}}
    <title>カテゴリ変更履歴一覧</title>
</head>
<body>

    {{-- ==========================================================
         カテゴリ変更履歴一覧画面のタイトル
         ----------------------------------------------------------
         この画面が、BlogOSに保存されている
         カテゴリ変更履歴の一覧画面であることを示す。
         ========================================================== --}}
    <h1>カテゴリ変更履歴一覧</h1>

    {{-- ==========================================================
         BlogOSトップページへの戻るリンク
         ----------------------------------------------------------
         カテゴリ変更履歴一覧画面からBlogOSのトップページへ
         戻るためのリンク。
         ========================================================== --}}
    <p>
        <a href="{{ url('/') }}">トップページに戻る</a>
    </p>

    {{-- ==========================================================
         対象ブログ情報
         ----------------------------------------------------------
         現在カテゴリ一覧を表示している対象ブログを表示する。

         $blogは、CategoryListControllerが
         blog_idを基にblogsテーブルから取得したBlog Model。

         ========================================================== --}}

    <h2>対象ブログ</h2>

    <p>
        ID：{{ $blog->id }}
    </p>

    <p>
        サイト名：{{ $blog->name }}
    </p>

    <p>
        URL：
        <a href="{{ $blog->url }}" target="_blank">
            {{ $blog->url }}
        </a>
    </p>

    <p>
        ホームURL：
        <a href="{{ $blog->home }}" target="_blank">
            {{ $blog->home }}
        </a>
    </p>

    {{-- ==========================================================
         カテゴリ変更履歴登録件数
         ----------------------------------------------------------
         Controllerから渡された$totalを使用して、
         category_historiesテーブルに登録されている
         カテゴリ変更履歴の総件数を表示する。
         ========================================================== --}}
    <p>登録件数：{{ $total }}件</p>

    {{-- ==========================================================
         カテゴリ変更履歴一覧表示テーブル
         ----------------------------------------------------------
         BlogOSに保存されているカテゴリ変更履歴を一覧表示する。
         表示する項目は以下の8項目。

         ・ID
         ・ブログID
         ・カテゴリID
         ・変更項目
         ・変更前の値
         ・変更後の値
         ・変更経路
         ・変更日時

         $historiesに格納されたCategoryHistory Modelを
         1件ずつ表示する。

         カテゴリ変更履歴が1件も存在しない場合は、

         「登録されているカテゴリ変更履歴がありません。」

         と表示する。
         ========================================================== --}}
    <table
        style="table-layout:fixed; width:100%; border-collapse:collapse;"
        border="1"
        cellpadding="5"
        cellspacing="0"
    >

        {{-- ======================================================
             各列の幅を定義
             ------------------------------------------------------
             一覧表の各項目が画面上で占める幅を指定する。

             ID・ブログID・カテゴリID・日時などの項目は狭く、
             変更前後の値などの項目は比較的広く設定する。
             ====================================================== --}}
        <colgroup>

            {{-- 履歴ID --}}
            <col style="width:5%">

            {{-- ブログID --}}
            <col style="width:8%">

            {{-- カテゴリID --}}
            <col style="width:9%">

            {{-- 変更項目 --}}
            <col style="width:10%">

            {{-- 変更前の値 --}}
            <col style="width:20%">

            {{-- 変更後の値 --}}
            <col style="width:20%">

            {{-- 変更経路 --}}
            <col style="width:13%">

            {{-- 変更日時 --}}
            <col style="width:15%">

        </colgroup>

        {{-- ======================================================
             テーブルヘッダー
             ------------------------------------------------------
             各列に表示する項目名を定義する。
             ====================================================== --}}
        <thead>
            <tr>

                {{-- カテゴリ変更履歴ID --}}
                <th>ID</th>

                {{-- 変更対象となったブログID --}}
                <th>ブログID</th>

                {{-- 変更対象となったカテゴリID --}}
                <th>カテゴリID</th>

                {{-- 変更された項目名 --}}
                <th>変更項目</th>

                {{-- 変更前の値 --}}
                <th>変更前の値</th>

                {{-- 変更後の値 --}}
                <th>変更後の値</th>

                {{-- 変更が発生した経路 --}}
                <th>変更経路</th>

                {{-- 変更が発生した日時 --}}
                <th>変更日時</th>

            </tr>
        </thead>

        {{-- ======================================================
             カテゴリ変更履歴データ表示領域
             ------------------------------------------------------
             $historiesに格納されているCategoryHistory Modelを
             1件ずつテーブルへ表示する。

             @forelseを使用しているため、

             ・変更履歴が存在する場合

                 → @forelse内の<tr>を表示

             ・変更履歴が存在しない場合

                 → @empty内のメッセージを表示

             という2つの状態をまとめて処理できる。
             ====================================================== --}}
        <tbody>

            @forelse ($histories as $history)

                {{-- ==================================================
                     1変更履歴分の表示
                     --------------------------------------------------
                     $historyには、現在表示対象となっている
                     1件のCategoryHistory Modelが格納されている。

                     CategoryHistory Modelの各プロパティから、
                     category_historiesテーブルに保存されている
                     変更履歴情報を取得して表示する。
                     ================================================== --}}
                <tr>

                    {{-- ==================================================
                         BlogOS上で管理する変更履歴ID
                         --------------------------------------------------
                         category_histories.idを表示する。

                         このIDはBlogOS内部で変更履歴レコードを
                         一意に識別するために使用する。

                         現時点では詳細画面を作成していないため、
                         IDはリンクにせず、そのまま表示する。
                         ================================================== --}}
                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $history->id }}
                    </td>

                    {{-- ==================================================
                         変更対象となったブログID
                         --------------------------------------------------
                         category_histories.blog_idを表示する。

                         このIDはblogs.idを参照しており、
                         どのブログに対するカテゴリ変更履歴なのかを
                         識別する。
                         ================================================== --}}
                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $history->blog_id }}
                    </td>

                    {{-- ==================================================
                         変更対象となったカテゴリID
                         --------------------------------------------------
                         category_histories.category_idを表示する。

                         このIDはcategories.idを参照しており、
                         どのカテゴリに対する変更履歴なのかを
                         識別する。

                         ここで表示するcategory_idは、
                         WordPress側のカテゴリIDではなく、
                         BlogOS内部のcategories.idである。
                         ================================================== --}}
                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $history->category_id }}
                    </td>

                    {{-- ==================================================
                         変更された項目
                         --------------------------------------------------
                         category_histories.fieldに保存されている
                         変更された項目名を表示する。

                         例：

                         ・name
                         ・slug
                         ・parent
                         ・link
                         ・description

                         など。
                         ================================================== --}}
                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $history->field }}
                    </td>

                    {{-- ==================================================
                         変更前の値
                         --------------------------------------------------
                         category_histories.old_valueに保存されている
                         変更前の値を表示する。

                         新規設定など、変更前の値が存在しない場合は
                         NULLとなるため、その場合は空欄として表示する。
                         ================================================== --}}
                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $history->old_value }}
                    </td>

                    {{-- ==================================================
                         変更後の値
                         --------------------------------------------------
                         category_histories.new_valueに保存されている
                         変更後の値を表示する。

                         値が削除された場合はNULLとなるため、
                         その場合は空欄として表示する。
                         ================================================== --}}
                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $history->new_value }}
                    </td>

                    {{-- ==================================================
                         変更経路
                         --------------------------------------------------
                         category_histories.sourceに保存されている
                         変更が発生した経路を表示する。

                         例：

                         ・api
                         ・manual
                         ・system

                         など。
                         ================================================== --}}
                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $history->source }}
                    </td>

                    {{-- ==================================================
                         変更日時
                         --------------------------------------------------
                         category_histories.created_atに保存されている、
                         変更履歴が作成された日時を表示する。

                         category_historiesではupdated_atを使用せず、
                         created_atによって履歴が発生した日時を管理する。
                         ================================================== --}}
                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $history->created_at }}
                    </td>

                </tr>

            @empty

                {{-- ==================================================
                     変更履歴が存在しない場合
                     --------------------------------------------------
                     category_historiesテーブルにレコードが1件も
                     存在しない場合に表示するメッセージ。
                     ================================================== --}}
                <tr>
                    <td colspan="8">
                        登録されているカテゴリ変更履歴がありません。
                    </td>
                </tr>

            @endforelse

        </tbody>

    </table>

</body>
</html>
