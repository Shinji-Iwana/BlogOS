<!DOCTYPE html>

<html lang="ja">

<head>

    {{-- ==========================================================
         基本的なHTML設定
         ----------------------------------------------------------
         UTF-8で日本語を正しく表示する。
         ========================================================== --}}
    <meta charset="UTF-8">

    {{-- ==========================================================
         ページタイトル
         ----------------------------------------------------------
         ブラウザのタブなどに表示するページタイトル。
         ========================================================== --}}
    <title>ブログ一覧（BlogOS）</title>

</head>

<body>

    {{-- ==========================================================
         ブログ一覧画面
         ----------------------------------------------------------
         BlogOSへ登録されているブログを一覧表示する画面。

         この画面では、Controllerから渡された
         $blogsと$totalを使用して、

         ・登録されているブログの件数
         ・各ブログの基本情報
         ・登録日時
         ・更新日時

         を表示する。

         このBladeではDBへ直接アクセスせず、
         Controller側で取得されたデータを
         画面へ表示することだけを担当する。

         ========================================================== --}}

    <h1>ブログ一覧</h1>

    {{-- ==========================================================
         BlogOSトップページへの戻るリンク
         ----------------------------------------------------------
         ブログ一覧画面からBlogOSのトップページへ戻るためのリンク。
         ========================================================== --}}

    <p>
        <a href="{{ url('/') }}">トップページに戻る</a>
    </p>

    {{-- ==========================================================
         ブログ登録件数
         ----------------------------------------------------------
         Controllerから渡された$totalを使用して、
         blogsテーブルに登録されているブログの総件数を表示する。

         例：
             登録件数：3件

         ========================================================== --}}

    <p>登録件数：{{ $total }}件</p>

    {{-- ==========================================================
         ブログ一覧表示テーブル
         ----------------------------------------------------------
         BlogOSへ登録されているブログ情報を一覧表示する。

         表示する項目は以下の9項目。

         ・ID
         ・サイト名
         ・説明
         ・URL
         ・ホームURL
         ・GMTオフセット
         ・タイムゾーン
         ・登録日時
         ・更新日時

         $blogsに格納されたBlog Modelを
         1件ずつ表示する。

         ブログが1件も存在しない場合は、
         「登録されているブログがありません。」
         と表示する。

         ========================================================== --}}

    <table
        style="table-layout:fixed; width:100%; border-collapse:collapse;"
        border="1"
        cellpadding="5"
        cellspacing="0"
    >

        {{-- ======================================================
             各列の幅を定義
             ------------------------------------------------------
             一覧表の各項目が画面上で占める幅を指定する。

             IDや日時などの項目は狭く、
             サイト名・説明・URLなどの項目は
             比較的広く設定している。

             ====================================================== --}}

        <colgroup>

            {{-- ブログID --}}
            <col style="width:5%">

            {{-- サイト名 --}}
            <col style="width:15%">

            {{-- サイト説明 --}}
            <col style="width:20%">

            {{-- サイトURL --}}
            <col style="width:15%">

            {{-- WordPressのホームURL --}}
            <col style="width:15%">

            {{-- GMTオフセット --}}
            <col style="width:8%">

            {{-- タイムゾーン --}}
            <col style="width:10%">

            {{-- 登録日時 --}}
            <col style="width:6%">

            {{-- 更新日時 --}}
            <col style="width:6%">

        </colgroup>

        {{-- ======================================================
             テーブルヘッダー
             ------------------------------------------------------
             各列に表示する項目名を定義する。

             ====================================================== --}}

        <thead>

            <tr>

                {{-- BlogOS上で管理するブログID --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    ID
                </th>

                {{-- WordPressサイトの名称 --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    サイト名
                </th>

                {{-- WordPressサイトの説明 --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    説明
                </th>

                {{-- WordPress REST APIから取得したサイトURL --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    URL
                </th>

                {{-- WordPressサイトのホームURL --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    ホームURL
                </th>

                {{-- WordPressサイトのGMTオフセット --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    GMTオフセット
                </th>

                {{-- WordPressサイトのタイムゾーン --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    タイムゾーン
                </th>

                {{-- BlogOSへブログが登録された日時 --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    登録日時
                </th>

                {{-- BlogOS上でブログ情報が最後に更新された日時 --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    更新日時
                </th>

            </tr>

        </thead>

        {{-- ======================================================
             ブログ一覧データ表示領域
             ------------------------------------------------------
             $blogsに格納されているBlog Modelを
             1件ずつテーブルへ表示する。

             @forelseを使用しているため、

             ・ブログが存在する場合
                 → @forelse内の<tr>を表示

             ・ブログが存在しない場合
                 → @empty内のメッセージを表示

             という2つの状態をまとめて処理できる。

             ====================================================== --}}

        <tbody>

            @forelse ($blogs as $blog)

                {{-- ==================================================
                     1ブログ分の表示
                     --------------------------------------------------
                     $blogには、現在表示対象となっている
                     1件のBlog Modelが格納されている。

                     Blog Modelの各プロパティから、
                     blogsテーブルに保存されている情報を取得して表示する。

                     ================================================== --}}

                <tr>

                    {{-- ==================================================
                         BlogOS上で管理するブログID
                         --------------------------------------------------
                         blogs.idを表示する。

                         このIDはBlogOS内部でブログを識別するために使用する。

                         IDをリンクとして表示し、
                         クリックすると該当するブログの詳細画面へ遷移する。
                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        <a href="{{ route('database-blog-detail', $blog->id) }}">{{ $blog->id }}</a>
                    </td>

                    {{-- ==================================================
                         サイト名
                         --------------------------------------------------
                         WordPress REST APIから取得して
                         blogs.nameへ保存したサイト名を表示する。
                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $blog->name }}
                    </td>

                    {{-- ==================================================
                         サイト説明
                         --------------------------------------------------
                         WordPress REST APIから取得して
                         blogs.descriptionへ保存したサイト説明を表示する。

                         長い説明文については、
                         CSSによって1行表示に制限している。
                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $blog->description }}
                    </td>

                    {{-- ==================================================
                         サイトURL
                         --------------------------------------------------
                         blogs.urlに保存されているURLを表示する。

                         URL自体を<a>タグで囲むことで、
                         ユーザーがクリックして実際のサイトを
                         別タブで開けるようにしている。

                         target="_blank"により、
                         BlogOSのブログ一覧画面を残したまま
                         対象サイトを確認できる。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">

                        <a href="{{ $blog->url }}" target="_blank">
                            {{ $blog->url }}
                        </a>

                    </td>

                    {{-- ==================================================
                         ホームURL
                         --------------------------------------------------
                         blogs.homeに保存されている
                         WordPressサイトのホームURLを表示する。

                         URLをクリックすると、
                         対象サイトを別タブで開くことができる。

                         BlogOSではhomeを既存ブログの識別に使用しているため、
                         ブログ管理上重要な情報となる。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">

                        <a href="{{ $blog->home }}" target="_blank">
                            {{ $blog->home }}
                        </a>

                    </td>

                    {{-- ==================================================
                         GMTオフセット
                         --------------------------------------------------
                         blogs.gmt_offsetに保存されている
                         WordPressサイトのGMTオフセットを表示する。

                         BlogRepositoryでDB保存・比較用に
                         小数点以下2桁へ正規化された値が表示される。

                         例：
                             9.00
                            -5.00

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $blog->gmt_offset }}
                    </td>

                    {{-- ==================================================
                         タイムゾーン
                         --------------------------------------------------
                         blogs.timezoneに保存されている
                         WordPressサイトのタイムゾーンを表示する。

                         例：
                             Asia/Tokyo

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $blog->timezone }}
                    </td>

                    {{-- ==================================================
                         登録日時
                         --------------------------------------------------
                         blogs.created_atに保存されている、
                         BlogOSへブログが登録された日時を表示する。
                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $blog->created_at }}
                    </td>

                    {{-- ==================================================
                         更新日時
                         --------------------------------------------------
                         blogs.updated_atに保存されている、
                         ブログ情報が最後に更新された日時を表示する。

                         WordPress APIから取得した情報との差分更新などによって
                         Blog Modelが更新された場合、この日時も更新される。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $blog->updated_at }}
                    </td>

                </tr>

            @empty

                {{-- ==================================================
                     ブログ未登録時の表示
                     --------------------------------------------------
                     $blogsに1件もブログが存在しない場合に表示する。

                     9列分を1つのセルとして結合し、
                     一覧テーブル全体にメッセージを表示する。

                     ================================================== --}}

                <tr>

                    <td colspan="9">
                        登録されているブログがありません。
                    </td>

                </tr>

            @endforelse

        </tbody>

    </table>

</body>

</html>
