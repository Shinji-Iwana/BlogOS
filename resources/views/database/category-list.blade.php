<!DOCTYPE html>

<html lang="ja">

<head>

    {{-- ==========================================================
         基本的なHTML設定
         ----------------------------------------------------------
         UTF-8で日本語を正しく表示する。
         ========================================================== --}}
    <meta charset="UTF-8">

    {{-- ==========================================================
         ページタイトル
         ----------------------------------------------------------
         ブラウザのタブなどに表示するページタイトル。
         ========================================================== --}}
    <title>カテゴリ一覧（BlogOS）</title>

</head>

<body>

    {{-- ==========================================================
         カテゴリ一覧画面
         ----------------------------------------------------------
         BlogOSへ登録されているカテゴリを一覧表示する画面。

         この画面では、Controllerから渡された

         ・$blog
         ・$categories
         ・$total

         を使用して、

         ・登録されているカテゴリの件数
         ・カテゴリID
         ・カテゴリ名
         ・スラッグ
         ・親カテゴリID
         ・カテゴリURL
         ・説明
         ・登録日時
         ・更新日時

         を表示する。

         このBladeではWordPress REST APIへ直接アクセスせず、
         Controllerから渡されたDB取得済みのデータを
         画面へ表示することだけを担当する。

         ========================================================== --}}

    <h1>カテゴリ一覧</h1>

    {{-- ==========================================================
         BlogOSトップページへの戻るリンク
         ----------------------------------------------------------
         カテゴリ一覧画面からBlogOSのトップページへ戻るためのリンク。
         ========================================================== --}}

    <p>
        <a href="{{ url('/') }}">トップページに戻る</a>
    </p>

    {{-- ==========================================================
         対象ブログ情報
         ----------------------------------------------------------
         現在カテゴリ一覧を表示している対象ブログを表示する。

         $blogは、CategoryListControllerが
         blog_idを基にblogsテーブルから取得したBlog Model。

         ========================================================== --}}

    <h2>対象ブログ</h2>

    <p>
        ID：{{ $blog->id }}
    </p>

    <p>
        サイト名：{{ $blog->display_name }}
    </p>

    <p>
        URL：
        <a href="{{ $blog->home }}" target="_blank">
            {{ $blog->home }}
        </a>
    </p>

    <p>
        ホームURL：
        <a href="{{ $blog->home }}" target="_blank">
            {{ $blog->home }}
        </a>
    </p>

    {{-- ==========================================================
         カテゴリ登録件数
         ----------------------------------------------------------
         Controllerから渡された$totalを使用して、
         categoriesテーブルに登録されているカテゴリの総件数を表示する。

         例：
             登録件数：10件

         ========================================================== --}}

    <p>登録件数：{{ $total }}件</p>

    {{-- ==========================================================
         カテゴリ一覧表示テーブル
         ----------------------------------------------------------
         BlogOSへ登録されているカテゴリ情報を一覧表示する。

         表示する項目は以下の9項目。

         ・カテゴリID
         ・カテゴリ名
         ・スラッグ
         ・親カテゴリID
         ・カテゴリURL
         ・説明
         ・ブログID
         ・登録日時
         ・更新日時

         $categoriesに格納されたCategory Modelを
         1件ずつ表示する。

         カテゴリが1件も存在しない場合は、
         「登録されているカテゴリがありません。」
         と表示する。

         ========================================================== --}}

    <table
        style="table-layout:fixed; width:100%; border-collapse:collapse;"
        border="1"
        cellpadding="5"
        cellspacing="0"
    >

        {{-- ======================================================
             各列の幅を定義
             ------------------------------------------------------
             一覧表の各項目が画面上で占める幅を指定する。

             IDや日時などの項目は狭く、
             カテゴリ名・説明・URLなどの項目は
             比較的広く設定している。

             ====================================================== --}}

        <colgroup>

            {{-- カテゴリID --}}
            <col style="width:6%">

            {{-- カテゴリ名 --}}
            <col style="width:12%">

            {{-- スラッグ --}}
            <col style="width:12%">

            {{-- 親カテゴリID --}}
            <col style="width:8%">

            {{-- カテゴリURL --}}
            <col style="width:17%">

            {{-- 説明 --}}
            <col style="width:20%">

            {{-- ブログID --}}
            <col style="width:7%">

            {{-- 登録日時 --}}
            <col style="width:9%">

            {{-- 更新日時 --}}
            <col style="width:9%">

        </colgroup>

        {{-- ======================================================
             テーブルヘッダー
             ------------------------------------------------------
             各列に表示する項目名を定義する。

             ====================================================== --}}

        <thead>

            <tr>

                {{-- WordPress側で管理するカテゴリID --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    カテゴリID
                </th>

                {{-- WordPressカテゴリの名称 --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    カテゴリ名
                </th>

                {{-- WordPressカテゴリのスラッグ --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    スラッグ
                </th>

                {{-- WordPress側で管理されている親カテゴリID --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    親カテゴリID
                </th>

                {{-- WordPressカテゴリページのURL --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    カテゴリURL
                </th>

                {{-- WordPressカテゴリの説明 --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    説明
                </th>

                {{-- BlogOS上でカテゴリが所属するブログID --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    ブログID
                </th>

                {{-- BlogOSへカテゴリが登録された日時 --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    登録日時
                </th>

                {{-- BlogOS上でカテゴリ情報が最後に更新された日時 --}}
                <th style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap;">
                    更新日時
                </th>

            </tr>

        </thead>

        {{-- ======================================================
             カテゴリ一覧データ表示領域
             ------------------------------------------------------
             $categoriesに格納されているCategory Modelを
             1件ずつテーブルへ表示する。

             @forelseを使用しているため、

             ・カテゴリが存在する場合
                 → @forelse内の<tr>を表示

             ・カテゴリが存在しない場合
                 → @empty内のメッセージを表示

             という2つの状態をまとめて処理できる。

             ====================================================== --}}

        <tbody>

            @forelse ($categories as $category)

                {{-- ==================================================
                     1カテゴリ分の表示
                     --------------------------------------------------
                     $categoryには、現在表示対象となっている
                     1件のCategory Modelが格納されている。

                     Category Modelの各プロパティから、
                     categoriesテーブルに保存されている情報を
                     取得して表示する。

                     ================================================== --}}

                <tr>

                    {{-- ==================================================
                         WordPressカテゴリID
                         --------------------------------------------------
                         categories.category_idを表示する。

                         このIDはWordPress側でカテゴリを
                         一意に識別するために使用する。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $category->category_id }}
                    </td>

                    {{-- ==================================================
                         カテゴリ名
                         --------------------------------------------------
                         WordPress REST APIから取得して
                         categories.nameへ保存したカテゴリ名を表示する。
                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $category->name }}
                    </td>

                    {{-- ==================================================
                         スラッグ
                         --------------------------------------------------
                         WordPress REST APIから取得して
                         categories.slugへ保存したスラッグを表示する。

                         スラッグはWordPress上でカテゴリURLなどに
                         使用される識別子となる。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $category->slug }}
                    </td>

                    {{-- ==================================================
                         親カテゴリID
                         --------------------------------------------------
                         categories.parentに保存されている
                         WordPress側の親カテゴリIDを表示する。

                         親カテゴリが存在しない場合は
                         WordPress REST APIの仕様により0となる。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $category->parent }}
                    </td>

                    {{-- ==================================================
                         カテゴリURL
                         --------------------------------------------------
                         categories.linkに保存されている
                         WordPressカテゴリページのURLを表示する。

                         URL自体を<a>タグで囲むことで、
                         ユーザーがクリックして実際のカテゴリページを
                         別タブで開けるようにしている。

                         target="_blank"により、
                         BlogOSのカテゴリ一覧画面を残したまま
                         対象カテゴリを確認できる。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">

                        <a href="{{ $category->link }}" target="_blank">
                            {{ $category->link }}
                        </a>

                    </td>

                    {{-- ==================================================
                         カテゴリ説明
                         --------------------------------------------------
                         WordPress REST APIから取得して
                         categories.descriptionへ保存した
                         カテゴリ説明を表示する。

                         長い説明文については、
                         CSSによって1行表示に制限している。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $category->description }}
                    </td>

                    {{-- ==================================================
                         ブログID
                         --------------------------------------------------
                         categories.blog_idに保存されている
                         BlogOS上のブログIDを表示する。

                         CategoryRepositoryでは、
                         ブログIDを指定してカテゴリを取得するため、
                         この値によってどのブログに所属するカテゴリなのかを
                         識別できる。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $category->blog_id }}
                    </td>

                    {{-- ==================================================
                         登録日時
                         --------------------------------------------------
                         categories.created_atに保存されている、
                         BlogOSへカテゴリが登録された日時を表示する。
                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $category->created_at }}
                    </td>

                    {{-- ==================================================
                         更新日時
                         --------------------------------------------------
                         categories.updated_atに保存されている、
                         カテゴリ情報が最後に更新された日時を表示する。

                         WordPress APIから取得した情報との差分更新などによって
                         Category Modelが更新された場合、
                         この日時も更新される。

                         ================================================== --}}

                    <td style="overflow:hidden; text-overflow:ellipsis; white-space:nowrap; max-width:0;">
                        {{ $category->updated_at }}
                    </td>

                </tr>

            @empty

                {{-- ==================================================
                     カテゴリ未登録時の表示
                     --------------------------------------------------
                     $categoriesに1件もカテゴリが存在しない場合に表示する。

                     9列分を1つのセルとして結合し、
                     一覧テーブル全体にメッセージを表示する。

                     ================================================== --}}

                <tr>

                    <td colspan="9">
                        登録されているカテゴリがありません。
                    </td>

                </tr>

            @endforelse

        </tbody>

    </table>

</body>

</html>
