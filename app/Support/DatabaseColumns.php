    /**
     * 列の説明（なければ null）
     */
    public static function describe(string $table, string $column): ?string
    {
        if (DatabaseTables::isWordPress($table)) {
            return WordPressColumns::describe($table, $column);
        }
        if (($foreignKey = self::historyForeignKey($table)) !== null) {
            return WordPressColumns::describeHistory($column, $foreignKey);
        }

        return self::TABLES[$table][$column] ?? self::COMMON[$column] ?? null;
    }

    /**
     * 変更履歴のテーブルなら、履歴の元を指す列（post_histories なら post_id。blog_histories は blog_id）。履歴のテーブルでなければ null
     */
    protected static function historyForeignKey(string $table): ?string
    {
        if (! str_ends_with($table, '_histories') || ! DatabaseTables::hasColumn($table, 'change_set_id')) {
            return null;
        }

        return substr($table, 0, -strlen('_histories')) . '_id';
    }
